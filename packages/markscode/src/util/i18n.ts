export const MESSAGES: Record<Language, Record<string, string>> = {
  "en-US": en,
  "pt-BR": ptBr,
}

export function isSupportedLanguage(value: unknown): value is Language {
  return value === "en-US" || value === "pt-BR"
}

export function translate(language: Language, key: string, fallback?: string): string {
  const localized = MESSAGES[language][key]
  if (localized !== undefined) return localized
  const english = MESSAGES["en-US"][key]
  if (english !== undefined) return english
  return fallback ?? key
}

export function resolveLanguage(configLanguage?: string | undefined): Language {
  const marksAgent = getMarksAgentString("MARKSCODE_LANGUAGE")
  if (isSupportedLanguage(marksAgent)) return marksAgent
  const env = process.env.MARKSCODE_LANGUAGE
  if (isSupportedLanguage(env)) return env
  if (isSupportedLanguage(configLanguage)) return configLanguage
  return "en-US"
}

export function interpolate(template: string, params?: Record<string, string>): string {
  if (!params) return template
  return template.replace(/\{(\w+)\}/g, (match, name: string) => (name in params ? params[name]! : match))
}

